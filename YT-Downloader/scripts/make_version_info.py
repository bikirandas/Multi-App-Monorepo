"""Write a PyInstaller version-info file from app/version.py.

PyInstaller's --version-file embeds these values in the Windows .exe resource,
so File/Product version shows in Explorer > Properties > Details.

Usage (from the YT-Downloader directory):
    python scripts/make_version_info.py version_info.txt
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

APP_NAME = "Boxndots Music & Video Downloader (BMVD)"
INTERNAL_NAME = "yt-downloader"
COMPANY = "Bikiran Das"
COPYRIGHT = "Copyright (c) Bikiran Das"

VERSION_FILE = Path(__file__).resolve().parent.parent / "app" / "version.py"


def read_version() -> str:
    match = re.search(r'__version__\s*=\s*"([^"]+)"', VERSION_FILE.read_text(encoding="utf-8"))
    if not match:
        raise SystemExit(f"__version__ not found in {VERSION_FILE}")
    return match.group(1)


def as_four_parts(version: str) -> tuple[int, int, int, int]:
    parts = [int(p) for p in version.split(".")]
    if not 1 <= len(parts) <= 4:
        raise SystemExit(f"Unsupported version '{version}': use 1 to 4 numeric parts")
    return tuple(parts + [0] * (4 - len(parts)))  # type: ignore[return-value]


def main() -> None:
    output = Path(sys.argv[1])
    version = read_version()
    parts = as_four_parts(version)
    dotted = ".".join(str(p) for p in parts)
    original_filename = f"yt-downloader-v{version}.exe"

    content = f"""# UTF-8
# Generated by scripts/make_version_info.py from app/version.py. Do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={parts},
    prodvers={parts},
    mask=0x3F,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [StringStruct('CompanyName', '{COMPANY}'),
         StringStruct('FileDescription', '{APP_NAME}'),
         StringStruct('FileVersion', '{dotted}'),
         StringStruct('InternalName', '{INTERNAL_NAME}'),
         StringStruct('LegalCopyright', '{COPYRIGHT}'),
         StringStruct('OriginalFilename', '{original_filename}'),
         StringStruct('ProductName', '{APP_NAME}'),
         StringStruct('ProductVersion', '{version}')])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""
    output.write_text(content, encoding="utf-8")
    print(f"Wrote {output} for version {version}")


if __name__ == "__main__":
    main()
